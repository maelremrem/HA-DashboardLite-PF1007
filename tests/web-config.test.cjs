const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');

const source = fs.readFileSync(path.join(__dirname, '..', 'app/src/main/assets/config/app.js'), 'utf8');
const start = source.indexOf('function moveItem(');
const end = source.indexOf('\nasync function loadConfiguration(', start);
assert.ok(start >= 0 && end > start);
const sandbox = vm.createContext({});
const defs = source.slice(source.indexOf('const CARD_TYPES = '), source.indexOf('let displaySettings = '));
vm.runInContext('const MAX_PAGES = 4; const MAX_CARDS = 12; ' + defs + source.slice(start, end), sandbox);

const exec = (statement) => vm.runInContext(statement, sandbox);
exec('var pages = [makePage("Maison")];');
assert.equal(exec('pages[0].columns'), 3);
assert.equal(exec('pages[0].cards.length'), 0);
assert.equal(exec('moveItem(pages, 0, 1)'), false);
exec('pages.push(makePage("Atelier"));');
assert.equal(exec('moveItem(pages, 0, 1)'), true);
assert.equal(exec('pages[0].title'), 'Atelier');
exec('pages[0].cards.push(makeCard("metric"));');
assert.equal(exec('pages[0].cards[0].type'), 'metric');
exec('pages[0].cards[0].entity_id = "sensor.temperature";');
assert.doesNotThrow(() => exec('validatePages(pages)'));
assert.throws(() => exec('validatePages([])'), /pages/);
exec('pages[0].columns = 2; pages[0].cards = Array.from({length: 7}, (_, i) => ({type:"metric",label:"S"+i,entity_id:"sensor.a"+i}));');
assert.throws(() => exec('validatePages(pages)'), /rangées/);
exec('pages[0].columns = 4;');
assert.doesNotThrow(() => exec('validatePages(pages)'));
exec('pages[0].cards[0].entity_id = "invalid name";');
assert.throws(() => exec('validatePages(pages)'), /Entité invalide/);
exec('pages[0].cards[0].entity_id = "light.salon";');
assert.doesNotThrow(() => exec('validatePages(pages)'));
exec('pages[0].cards[0].type = "html";');
assert.throws(() => exec('validatePages(pages)'), /Type de carte/);
exec('pages[0].cards[0].type = "control";');
assert.doesNotThrow(() => exec('validatePages(pages)'));
exec('pages = Array.from({length: 5}, (_, i) => makePage("Page " + i));');
assert.throws(() => exec('validatePages(pages)'), /pages/);
exec('pages = [makePage("Caméras")]; pages[0].cards.push({...makeCard("camera"),entity_id:"camera.front",icon:"camera",col_span:2,row_span:2});');
assert.doesNotThrow(() => exec('validatePages(pages)'));
exec('pages[0].cards[0].entity_id = "sensor.foo"');
assert.throws(() => exec('validatePages(pages)'), /camera/);
exec('pages[0].cards[0].entity_id = "camera.front"');
exec('pages[0].cards[0].icon = "unsafe"');
assert.throws(() => exec('validatePages(pages)'), /Icône/);
exec('pages[0].cards[0].icon = "camera"');
assert.doesNotThrow(() => exec('validatePages(pages)'));

console.log('Dynamic pages, cards and limits passed');
